# card_value CARD KEY — a run card's value for KEY.
card_value() {
  awk -v key="$2" '{ line = $0; sub(/!.*/, "", line); n = split(line, f, "=");
    if (n == 2) { k = f[2]; gsub(/[ \t]/, "", k); v = f[1]; gsub(/[ \t]/, "", v);
      if (k == key) { print v; exit } } }' "$1"
}

# A file holding the generation script; its hash names the template it makes.
write_generation_script() {
  local row="$1" kind="$2" tmpl="$3" out="$4"
  case "$kind" in
    script | mlm)
      local driver
      driver="$(script_driver "$HERE/scripts/$row.mg5" "$tmpl" "$WORK/$row/models" no-launch)" ||
        die "$row: no generation script"
      mv "$driver" "$out"
      ;;
    dy13) printf 'generate p p > e+ e-\noutput %s -nojpeg\n' "$tmpl" > "$out" ;;
    dy13etau) printf 'define l+ = e+ ta+\ndefine l- = e- ta-\ngenerate p p > l+ l-\noutput %s -nojpeg\n' "$tmpl" > "$out" ;;
    onshell) printf 'import model sm\ngenerate u u~ > w+ b w- b~ $ t t~\noutput %s -nojpeg\n' "$tmpl" > "$out" ;;
    *) die "$row: no generation script for kind $kind" ;;
  esac
}

# make_template ROW KIND — the never-run process directory every seed copies.
make_template() {
  local row="$1" kind="$2" tmpl="$WORK/$1/template" script stamp
  mkdir -p "$WORK/$row"
  script="$WORK/$row/generate.mg5"
  write_generation_script "$row" "$kind" "$tmpl" "$script"
  stamp="$(mes_sha256 "$script")"
  [ "$kind" = onshell ] && stamp="$stamp $(mes_sha256 "$P1D_PATCH")"
  if [ -f "$tmpl/bin/generate_events" ] && [ "$(cat "$tmpl/.vg_source" 2>/dev/null)" = "$stamp" ]; then
    echo ">>> [$row] template exists" >&2
    return 0
  fi
  rm -rf "$tmpl"
  echo ">>> [$row] generating the template ($kind)" >&2
  if grep -qE '^[[:space:]]*import[[:space:]]+model[[:space:]]+/' "$script"; then
    MODELS_DIR="$WORK/$row/models" stage_models >&2
  fi
  if [ "$kind" = onshell ]; then
    VG_MG5_ROOT="$(mes_p1d_tree "$WORK/trees" "$P1D_PATCH")" \
      bash "$HERE/mg5_pinned.sh" "$script" > "$WORK/$row/generate.log" 2>&1 ||
      { tail -30 "$WORK/$row/generate.log" >&2; die "$row: generation failed"; }
  else
    bash "$HERE/mg5_pinned.sh" "$script" > "$WORK/$row/generate.log" 2>&1 ||
      { tail -30 "$WORK/$row/generate.log" >&2; die "$row: generation failed"; }
  fi
  [ -f "$tmpl/bin/generate_events" ] || die "$row: generation wrote no $tmpl"
  strip_ansi_escapes "$tmpl"
  echo "$stamp" > "$tmpl/.vg_source"
}

# keep_run RUNDIR TAG DEST — the files a seed record is computed from.
keep_run() {
  local rundir="$1" tag="$2" dest="$3" pdir name
  strip_ansi_escapes "$rundir"
  mkdir -p "$dest/SubProcesses"
  cp "$rundir/SubProcesses/results.dat" "$dest/SubProcesses/"
  for pdir in "$rundir"/SubProcesses/P*/; do
    [ -f "$pdir/symfact.dat" ] || continue
    name="$(basename "$pdir")"
    mkdir -p "$dest/SubProcesses/$name"
    cp "$pdir/symfact.dat" "$dest/SubProcesses/$name/"
    while read -r g; do
      mkdir -p "$dest/SubProcesses/$name/G$g"
      cp "$pdir/G$g/results.dat" "$dest/SubProcesses/$name/G$g/"
    done < <(awk '$2 > 0 { print $1 }' "$pdir/symfact.dat")
  done
  mkdir -p "$dest/Source"
  cp "$rundir/Source/run_config.inc" "$dest/Source/"
  cp "$rundir/Events/run_$tag/vg_events_written.txt" "$dest/events_written.txt"
  local banner
  banner="$(ls "$rundir/Events/run_$tag"/*_banner.txt 2>/dev/null | head -1)"
  [ -n "$banner" ] || die "no banner in $rundir/Events/run_$tag"
  cp "$banner" "$dest/banner.txt"
  local lhe="$rundir/Events/run_$tag/unweighted_events.lhe.gz"
  if [ -f "$lhe" ]; then
    python3 - "$lhe" "$dest/init.txt" <<'PY'
import gzip, sys
out = []
with gzip.open(sys.argv[1], "rt") as f:
    inside = False
    for line in f:
        if "<init>" in line:
            inside = True
        if inside:
            out.append(line)
        if "</init>" in line:
            break
open(sys.argv[2], "w").write("".join(out))
PY
  fi
}

# run_fresh ROW SEED NEVENTS CARD PARAM OVERRIDES — one seed in a fresh copy of
# the template, kept under OUTDIR; read back when kept under the same card.
# OVERRIDES (`key=value;...`, may be empty) go onto the card with iseed,
# hard_survey and nevents.
run_fresh() {
  local row="$1" seed="$2" nev="$3" card="$4" param="$5" overrides="$6"
  local keep="$OUTDIR/$row/s$seed" rundir="$WORK/$row/run_s$seed" tag="s$seed"
  local tmpcard="$WORK/$row/card_s$seed.dat" sha have=""
  mes_install_card "$card" "$tmpcard" "${overrides:+$overrides;}hard_survey=$HARD_SURVEY;nevents=$nev" "$seed"
  sha="$(mes_sha256 "$tmpcard")"
  [ -s "$keep/vg_seed_result.txt" ] && read -r _ _ _ have < "$keep/vg_seed_result.txt"
  # A seed kept with its param card is read back only under that same card.
  if [ -n "$param" ] && [ -f "$keep/param_card.dat" ] && ! cmp -s "$param" "$keep/param_card.dat"; then
    have=""
  fi
  if [ "${VG_FORCE:-0}" != 1 ] && [ "$have" = "$sha" ]; then
    echo ">>> [$row s$seed] kept under this card; read back" >&2
    return 0
  fi
  local attempt ok=0
  for attempt in 1 2; do
    rm -rf "$rundir"
    cp -a "$WORK/$row/template" "$rundir"
    mes_configure_dir "$rundir" "$NB_CORE"
    cp "$tmpcard" "$rundir/Cards/run_card.dat"
    [ -n "$param" ] && cp "$param" "$rundir/Cards/param_card.dat"
    if mes_run_seed "$rundir" "$tag" "$WORK/$row/logs/s$seed.$attempt.log" > /dev/null &&
      mes_check_run "$rundir" "$tag" "$nev"; then
      ok=1
      break
    fi
    echo "!!! [$row s$seed] attempt $attempt failed" >&2
  done
  [ "$ok" = 1 ] || die "$row s$seed: two attempts failed; logs in $WORK/$row/logs"
  rm -rf "$keep.tmp"
  keep_run "$rundir" "$tag" "$keep.tmp"
  cp "$rundir/Events/run_$tag/vg_seed_result.txt" "$keep.tmp/"
  if [ -n "$param" ]; then cp "$param" "$keep.tmp/param_card.dat"; fi
  rm -rf "$keep"
  mv "$keep.tmp" "$keep"
  rm -rf "$rundir"
  echo ">>> [$row s$seed] nevents $nev: $(cut -d' ' -f1-3 "$keep/vg_seed_result.txt")" >&2
}

# run_pta SEED NEVENTS — one ee_to_mumua seed: gen_pta_windows.sh's five
# m(mumu) windows, each in its own fresh directory, kept as w1..w5.
run_pta() {
  local seed="$1" nev="$2" row=ee_to_mumua
  local keep="$OUTDIR/$row/s$seed" ptawork="$WORK/$row/pta" stampfile="$WORK/$row/stamp_s$seed"
  local sha have="" w attempt ok=0 started wall
  {
    mes_sha256 "$HERE/output/$row/Cards/run_card.dat"
    mes_sha256 "$HERE/output/$row/Cards/param_card.dat"
    mes_sha256 "$HERE/gen_pta_windows.sh"
    echo "mll-371 $nev $seed hard_survey=$HARD_SURVEY"
  } > "$stampfile"
  sha="$(mes_sha256 "$stampfile")"
  [ -s "$keep/vg_seed_result.txt" ] && read -r _ _ _ have < "$keep/vg_seed_result.txt"
  if [ "${VG_FORCE:-0}" != 1 ] && [ "$have" = "$sha" ]; then
    echo ">>> [$row s$seed] kept under this card; read back" >&2
    return 0
  fi
  mkdir -p "$ptawork"
  for attempt in 1 2; do
    started="$(date +%s)"
    if PTA_WORK="$ptawork" RESULT_JSON="$ptawork/pta_window_reference.json" \
      NEVENTS="$nev" SEEDS="$seed" WINDOWS="1 2 3 4 5" TAG_SUFFIX="" HARD_SURVEY="$HARD_SURVEY" \
      bash "$HERE/gen_pta_windows.sh" --stage mll-371 > "$WORK/$row/logs/s$seed.$attempt.log" 2>&1; then
      ok=1
      for w in 1 2 3 4 5; do
        local wtag="mll-371_w${w}_n${nev}_s${seed}"
        mes_check_run "$ptawork/pta_$wtag" "$wtag" "$nev" || ok=0
      done
      [ "$ok" = 1 ] && break
    fi
    echo "!!! [$row s$seed] attempt $attempt failed; see $WORK/$row/logs/s$seed.$attempt.log" >&2
  done
  [ "$ok" = 1 ] || die "$row s$seed: two attempts of gen_pta_windows.sh failed"
  wall=$(($(date +%s) - started))
  rm -rf "$keep.tmp"
  for w in 1 2 3 4 5; do
    local tag="mll-371_w${w}_n${nev}_s${seed}"
    keep_run "$ptawork/pta_$tag" "$tag" "$keep.tmp/w$w"
    rm -rf "$ptawork/pta_$tag"
  done
  printf -- '- - %s %s\n' "$wall" "$sha" > "$keep.tmp/vg_seed_result.txt"
  rm -rf "$keep"
  mv "$keep.tmp" "$keep"
  echo ">>> [$row s$seed] nevents $nev: five windows in $wall s" >&2
}

