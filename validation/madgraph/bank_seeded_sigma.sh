#!/usr/bin/env bash
# Bank MadEvent cross-section references as independent seeds: every run in a
# freshly copied process directory that no run has touched, at the row's budget
# and at four times it, with each run's per-channel iterations kept.
#
# Per row:
#
#   1. The row's process directory is generated once, through the path its
#      reference has always come from, and never run: the template.
#        script   scripts/<row>.mg5 without its launch block (build.sh's
#                 script_driver), on the banked run's own Cards/run_card.dat and
#                 Cards/param_card.dat from output/<row>/. The launch block's
#                 settings are checked against those cards first: `set key
#                 value` against the run card, `set block code value` (a
#                 param-card setting, ee_to_tth_ymt250's `set yukawa 6 250`)
#                 against the param card.
#        mlm      the same script, on the committed <row>_run_card.dat
#                 (gen_mlm_references.sh's card).
#        dy13     `generate p p > e+ e-` on dy13_default_run_card.dat or
#                 dy13_mmll_run_card.dat or dy_beams_6500_4000_run_card.dat
#                 (gen_hadronic_sigma.sh's): the references the pp_to_ll gate
#                 and the unequal-beam Drell-Yan gate read. dy13_mmll_60_120_mz95
#                 is the m_ll window card on the param card
#                 dy13_mz95_param_card.dat (MZ = 95 GeV), installed as every
#                 seed's Cards/param_card.dat.
#        dy13etau dy13_etau_default: `p p > l+ l-` with `l = e, ta` on
#                 dy13_default_run_card.dat, whose two lepton masses give two
#                 P directories.
#        onshell  uu_tt, `u u~ > w+ b w- b~ $ t t~` on onshell_uu_run_card.dat
#                 with gen_onshell_veto.sh's overrides, generated by the pinned
#                 tree with patches/aloha-p1d-flipped-fermion.patch applied.
#        pta      ee_to_mumua: gen_pta_windows.sh's m(mumu) partition
#                 (--stage mll-371), five windows per seed, each its own fresh
#                 directory; the seed's value is the sum over its windows.
#   2. Per seed, the template is copied, the card installed with `iseed` and
#      `hard_survey = 2` set (and `nevents` times four for SEEDS_4X), the row's
#      param card (if it has one) copied in beside it, and generate_events run
#      from a scratch working directory. The committed and banked cards are not
#      edited. A run fails when generate_events fails, when
#      results.dat holds no positive finite cross section, or when the event
#      file holds fewer events than the card asked for (mes_check_run):
#      generate_events has exited 0 on runs that hold neither. A failed run is
#      retried once in a fresh copy: MadEvent's parallel make has failed a link
#      (`archive has no index`) on a run that then succeeded.
#   3. The run keeps, under output/seeded_sigma/<row>/s<iseed>/:
#      SubProcesses/results.dat, every P*/symfact.dat and the G*/results.dat it
#      lists, the banner, the event file's <init> block, Source/run_config.inc
#      (the min_events/max_events the survey mode left), the event count,
#      madevent_seeds.sh's vg_seed_result.txt and the param card it ran on
#      (param_card.dat, for a row that installs one). The run directory is then
#      dropped. A seed whose kept files exist under the same run card, and
#      under the same param card where it kept one, is read back, not re-run
#      (VG_FORCE=1 re-runs it).
#   4. `seed-record` (validation-report/src/bin/seed-record.rs) writes
#      output/seeded_sigma/<row>/seed_record.json: per seed the reported value,
#      the equal-weight recombination of each channel's iterations, the budget
#      the survey and the wall time; and it prints three lines per row:
#        SCREEN   the 4x seeds against the 1x mean in standard errors. FLAGGED:
#                 the row needs a budget ladder before its record is banked.
#        LADDER   with 20 seeds at 1x and 20 at 4x: the two means, their measured
#                 seed spreads and sigma = sqrt(s1^2/n1 + s4^2/n4) (the quoted
#                 errors do not enter); "re-bank at 4x" when the means differ by
#                 more than 2 sigma, else "stays at 1x". Below 20 + 20 it says
#                 the ladder is not run.
#        SURVEY   hard_survey and the run_config.inc min/max_events every seed
#                 ran with. INERT: the survey ran at another rate than
#                 hard_survey asks (a card with mmjj > 0.01 (ebeam1 + ebeam2)).
#        SCATTER  the worst channel's seed chi2 p-value at the budget, times
#                 the channels tested (look-elsewhere). Below 0.01 it reads
#                 FLAGGED (confirm with 20 seeds), or CONFIRMED with 20 seeds
#                 or more; whether the row's sigma cell gates is the
#                 manifest's decision, not this driver's. `seed-record
#                 --rescreen PATH` re-reads a written record under this rule.
#
# Confirming a SCATTER flag, and running a ladder, on the M3 (a record that has
# only the default 5 + 2 seeds):
#
#   A row whose SCATTER line reads FLAGGED needs 20 seeds at its budget; one
#   whose SCREEN line reads FLAGGED needs 20 at the budget and 20 at 4x. Both
#   are the same command on the row's own output directory, with SEED_PLAN
#   naming the larger seed set. Seeds whose kept files exist under the same run
#   card are read back, not re-run, so only the new seeds cost a MadEvent run.
#
#     SEED_PLAN=confirm20  SEEDS = 20261101-20261105 and 20261201-20261215 (20 at
#                          the budget); SEEDS_4X stays 20261111 20261112 (read
#                          back). The record then holds 20 + 2 seeds and its
#                          SCATTER line reads CONFIRMED or within chance.
#     SEED_PLAN=ladder20   the same SEEDS, and SEEDS_4X = 20261111 20261112 and
#                          20261301-20261318 (20 at 4x). The record then holds
#                          20 + 20 seeds and its LADDER line gives the verdict.
#
#   One row, to a directory that leaves the banked record alone until the new
#   one is read (from validation/madgraph, with the record's s* directories
#   copied in so the seeds already run are read back):
#
#     mkdir -p /scratch/confirm && cp -R output/seeded_sigma/<row> /scratch/confirm/
#     SEED_PLAN=ladder20 SEEDED_OUT=/scratch/confirm ROWS=<row> \
#       pixi run -e madgraph bank-seeded-sigma
#     cargo run -q -p vibegraph-validation-report --bin seed-record -- \
#       --rescreen /scratch/confirm/<row>/seed_record.json
#
#   (the driver prints the same lines when it finishes). The record to bank is
#   /scratch/confirm/<row>/ whole: it carries the five original seeds, so it is
#   a superset of the banked one. Copy it over output/seeded_sigma/<row>/ only
#   when its LADDER or SCATTER line has been read; a "re-bank at 4x" verdict
#   changes which rung the gates read, which is the manifest's and the decision
#   record's call, not this driver's. Without SEEDED_OUT the new seeds are
#   written into output/seeded_sigma/<row>/ directly. An explicit SEEDS or
#   SEEDS_4X overrides the plan.
#
# The σ gates read a row's record where the bundle carries one
# (vibegraph-lib/tests/common/seed_record.rs) and its single banked run
# otherwise. assemble_bundle.sh carries output/seeded_sigma/.
#
# Usage: pixi run -e madgraph bank-seeded-sigma
#   ROWS     rows or groups, space-separated (required): @fixed22 @fixed23
#            @fixed24 @hadronic @llj-mlm @mlm-multi @ee-mumua @long @all,
#            or row names (uu_tt is in no group)
#   SEEDS    iseeds at the budget (default 20261101-20261105)
#   SEEDS_4X iseeds at four times the budget (default 20261111 20261112)
#   SEED_PLAN  confirm20 or ladder20: the larger seed sets above, where SEEDS and
#            SEEDS_4X are not given
#   NB_CORE  cores per madevent run (default 2)
#   JOBS     rows run at once (default 1)
#   HARD_SURVEY  hard_survey on every run's card (default 2); for diagnostic
#            runs only, as it is not the banked survey
#   NEVENTS  the budget, in place of the card's own nevents (ee_to_mumua:
#            100000); for diagnostic runs only, as it is not the banked budget
#   VALIDATED_EW_ROWS  rows whose record marks the equal-weight values as the
#            ones the gate reads (default none)
#   SEEDED_OUT   where records are written (default output/seeded_sigma)
#   SEEDED_WORK  templates, run directories and logs (default work/seeded_sigma)
#   DRY_RUN  1: print each row's kind, generation script, run card, param card
#            and launch-block checks, and run nothing (no MadGraph, no cargo)
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
SELF="$HERE/$(basename "${BASH_SOURCE[0]}")"
. "$HERE/madevent_seeds.sh"
# shellcheck source=build.sh
. "$HERE/build.sh"

OUTDIR="${SEEDED_OUT:-$HERE/output/seeded_sigma}"
WORK="${SEEDED_WORK:-$HERE/work/seeded_sigma}"
seed_range() { seq -f '%.0f' -s ' ' "$1" "$2"; }
case "${SEED_PLAN:-}" in
  "") plan_seeds="$(seed_range 20261101 20261105)"; plan_seeds_4x="20261111 20261112" ;;
  confirm20)
    plan_seeds="$(seed_range 20261101 20261105) $(seed_range 20261201 20261215)"
    plan_seeds_4x="20261111 20261112"
    ;;
  ladder20)
    plan_seeds="$(seed_range 20261101 20261105) $(seed_range 20261201 20261215)"
    plan_seeds_4x="20261111 20261112 $(seed_range 20261301 20261318)"
    ;;
  *) printf '!!! SEED_PLAN is confirm20 or ladder20, not %s\n' "$SEED_PLAN" >&2; exit 1 ;;
esac
SEEDS="${SEEDS:-$plan_seeds}"
SEEDS_4X="${SEEDS_4X-$plan_seeds_4x}"
NB_CORE="${NB_CORE:-2}"
JOBS="${JOBS:-1}"
HARD_SURVEY="${HARD_SURVEY:-2}"
P1D_PATCH="$HERE/patches/aloha-p1d-flipped-fermion.patch"
PTA_BUDGET=100000
export OUTDIR WORK SEEDS SEEDS_4X NB_CORE HARD_SURVEY

LHAPDF_DATA_PATH="$ROOT/validation/pdf"
if command -v lhapdf-config >/dev/null 2>&1; then
  LHAPDF_DATA_PATH="$LHAPDF_DATA_PATH:$(lhapdf-config --datadir)"
fi
export LHAPDF_DATA_PATH

