# row_setup ROW — the row's kind, run card, param card, overrides, tree and
# generator text, set in the caller's `kind card param overrides tree generator`
# (bash's dynamic scope); dies on a row whose cards disagree with its script.
row_setup() {
  local row="$1"
  kind="$(row_kind "$row")"
  case "$kind" in
    script)
      card="$HERE/output/$row/Cards/run_card.dat"
      param="$HERE/output/$row/Cards/param_card.dat"
      [ -f "$card" ] && [ -f "$param" ] || die "$row: no banked cards under output/$row (pixi run fetch-refdata)"
      mes_check_card "$HERE/scripts/$row.mg5" "$card" "iseed nevents" ||
        die "$row: scripts/$row.mg5 and output/$row/Cards/run_card.dat disagree"
      mes_check_param_card "$HERE/scripts/$row.mg5" "$param" ||
        die "$row: scripts/$row.mg5 and output/$row/Cards/param_card.dat disagree"
      generator="scripts/$row.mg5 without its launch block; run card and param card of output/$row/Cards"
      ;;
    mlm)
      card="$HERE/${row}_run_card.dat"
      mes_check_card "$HERE/scripts/$row.mg5" "$card" "iseed nevents" ||
        die "$row: scripts/$row.mg5 and ${row}_run_card.dat disagree"
      generator="scripts/$row.mg5 without its launch block; run card ${row}_run_card.dat"
      ;;
    dy13)
      case "$row" in
        dy13_default) card="$HERE/dy13_default_run_card.dat" ;;
        dy13_mmll_60_120) card="$HERE/dy13_mmll_run_card.dat" ;;
        dy13_beams_6500_4000) card="$HERE/dy_beams_6500_4000_run_card.dat" ;;
        dy13_mmll_60_120_mz95) card="$HERE/dy13_mmll_run_card.dat"; param="$HERE/dy13_mz95_param_card.dat" ;;
      esac
      generator="generate p p > e+ e- (gen_hadronic_sigma.sh); run card $(basename "$card")"
      if [ -n "$param" ]; then generator="$generator; param card $(basename "$param")"; fi
      ;;
    dy13etau)
      card="$HERE/dy13_default_run_card.dat"
      generator="define l+ = e+ ta+; define l- = e- ta-; generate p p > l+ l- ; run card dy13_default_run_card.dat"
      ;;
    onshell)
      card="$HERE/onshell_uu_run_card.dat"
      overrides="lpp1=0;lpp2=0;ebeam1=250;ebeam2=250;nevents=10000"
      tree="pinned + patches/$(basename "$P1D_PATCH")"
      generator="generate u u~ > w+ b w- b~ \$ t t~ (gen_onshell_veto.sh); run card onshell_uu_run_card.dat with $overrides"
      ;;
    pta)
      [ -f "$HERE/output/$row/Cards/run_card.dat" ] || die "$row: no banked cards under output/$row"
      generator="gen_pta_windows.sh --stage mll-371: the five m(mumu) windows through dummy_cuts, one fresh directory each, summed per seed; run card and param card of output/$row/Cards"
      ;;
    *) die "$row: not a row this driver knows (no scripts/$row.mg5)" ;;
  esac
}

# dry_row ROW — what run_row would run the row on, printed; nothing is run.
dry_row() {
  local row="$1" kind card="" param="" overrides="" tree=pinned generator script
  printf '=== %s\n' "$row"
  if ! (row_setup "$row") 2>&1 | sed 's/^/    /'; then
    printf '    WOULD FAIL: the row setup above refused it\n'
    return 0
  fi
  row_setup "$row"
  printf '    kind       %s\n    run card   %s\n    param card %s\n' "$kind" "$card" "${param:-none, the template default}"
  if [ -n "$overrides" ]; then printf '    overrides  %s\n' "$overrides"; fi
  printf '    tree       %s\n    generator  %s\n' "$tree" "$generator"
  if [ "$kind" != pta ]; then
    script="$(mktemp "${TMPDIR:-/tmp}/vg_dry_XXXXXX")"
    write_generation_script "$row" "$kind" "$WORK/$row/template" "$script"
    printf '    generation script:\n'
    sed 's/^/        /' "$script"
    rm -f "$script"
    local probe
    probe="$(mktemp "${TMPDIR:-/tmp}/vg_dry_XXXXXX")"
    mes_install_card "$card" "$probe" "$overrides" 0
    printf '    budget     nevents %s\n' "${NEVENTS:-$(card_value "$probe" nevents)}"
    rm -f "$probe"
  fi
  if [ "$kind" = dy13 ] && [ -n "$param" ]; then
    printf '    param card entries that differ from dy13_param_card.dat:\n'
    diff "$HERE/dy13_param_card.dat" "$param" | sed -n 's/^> /        /p' || true
  fi
}

# run_row ROW — every seed of one row, then its record.
run_row() {
  local row="$1" kind card="" param="" overrides="" tree=pinned generator base seed
  row_setup "$row"
  mkdir -p "$WORK/$row/logs" "$OUTDIR/$row"
  generator="bank_seeded_sigma.sh, one fresh directory per seed, hard_survey = $HARD_SURVEY on every run's card: $generator"

  if [ "$kind" = pta ]; then
    base="${NEVENTS:-$PTA_BUDGET}"
  else
    make_template "$row" "$kind"
    local probe="$WORK/$row/card_probe.dat"
    mes_install_card "$card" "$probe" "$overrides" 0
    base="${NEVENTS:-$(card_value "$probe" nevents)}"
    [ -n "$base" ] || die "$row: no nevents on the card"
  fi

  for seed in $SEEDS; do
    if [ "$kind" = pta ]; then run_pta "$seed" "$base"; else run_fresh "$row" "$seed" "$base" "$card" "$param" "$overrides"; fi
  done
  for seed in $SEEDS_4X; do
    if [ "$kind" = pta ]; then run_pta "$seed" "$((4 * base))"; else run_fresh "$row" "$seed" "$((4 * base))" "$card" "$param" "$overrides"; fi
  done

  local ew_flag=()
  case " ${VALIDATED_EW_ROWS:-} " in *" $row "*) ew_flag=(--validated-ew) ;; esac
  "$(seed_record_bin)" --row "$row" --kept "$OUTDIR/$row" --budget "$base" \
    --generator "$generator" --tree "$tree" --mg-version "$(mg_version)" \
    --hard-survey "$HARD_SURVEY" ${ew_flag[@]+"${ew_flag[@]}"} |
    tee "$WORK/$row/record.log"
}

if [ "${1:-}" = --row ]; then
