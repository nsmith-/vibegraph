#!/usr/bin/env python3
"""Read the param cards MadGraph's `compute_widths` wrote into the reference
table the `DECAY ... Auto` gate reads (`auto_widths_reference.json`).

Each case is one model and card, computed twice: `--body_decay=2` (the
two-body widths the gate compares channel by channel) and MadGraph's default
`--body_decay=4.0025` (whose modes beyond two bodies the width lists as not
included). A row's partial width is the comment MadGraph writes beside the
branching ratio, `val[0] * width` at Python's full `repr` precision
(`update_width_in_param_card`, `madevent_interface.py`); the total is the
`DECAY` line, which MadGraph prints with `%e`.

Usage: parse_auto_widths.py OUT.json NAME CARD|- PDGS TWO_BODY.dat DEFAULT.dat
       [NAME CARD|- PDGS TWO_BODY.dat DEFAULT.dat ...]
       PDGS is a comma-separated list; CARD is relative to the repository root.
"""

import json
import re
import sys

DECAY = re.compile(r"^DECAY\s+(-?\d+)\s+(\S+)")


def widths(path, pdgs):
    """{pdg: {total, total_text, channels}} for each code of `pdgs`."""
    out = {}
    current = None
    for line in open(path):
        m = DECAY.match(line)
        if m:
            pdg = int(m.group(1))
            current = None
            if pdg in pdgs:
                current = {"total": float(m.group(2)), "total_text": m.group(2), "channels": []}
                out[str(pdg)] = current
            continue
        if current is None or not line.strip() or line.lstrip().startswith("#"):
            continue
        body, _, comment = line.partition("#")
        fields = body.split()
        nda = int(fields[1])
        current["channels"].append(
            {
                "daughters": [int(x) for x in fields[2 : 2 + nda]],
                "branching_ratio": float(fields[0]),
                "width": float(comment.strip()),
            }
        )
    missing = [p for p in pdgs if str(p) not in out]
    if missing:
        sys.exit(f"{path}: no DECAY line for {missing}")
    return out


def main():
    out, rest = sys.argv[1], sys.argv[2:]
    if not rest or len(rest) % 5:
        sys.exit(__doc__)
    cases = []
    for i in range(0, len(rest), 5):
        name, card, pdgs, two_body, default = rest[i : i + 5]
        pdgs = [int(p) for p in pdgs.split(",")]
        cases.append(
            {
                "name": name,
                "card": None if card == "-" else card,
                "auto": pdgs,
                "two_body": widths(two_body, pdgs),
                "default": widths(default, pdgs),
            }
        )
    doc = {
        "_comment": "MadGraph 3.7.1 compute_widths, per channel: two_body at --body_decay=2, "
        "default at the default --body_decay=4.0025. Generated by "
        "validation/madgraph/gen_auto_widths.sh.",
        "mg_version": "3.7.1",
        "cases": cases,
    }
    with open(out, "w") as fh:
        json.dump(doc, fh, indent=1)
        fh.write("\n")


if __name__ == "__main__":
    main()
